/**
 * The viewer with screens loaded on demand: it loads only the screen types of the story (the
 * current screen and its neighbours first), and the next screen is loaded before the reader can
 * get there. Rendered on the server (as the host sites do), with loaders that we resolve by hand.
 */
import { ElementType, ReactNode, createElement } from 'react';
import { renderToString } from 'react-dom/server';
import { describe, expect, test } from 'vitest';

import { ScreensProvider } from '@micromag/core/contexts';

import { getScreenTypesByDistance, waitForScreens } from '../../lib/screensLoading';

// Not @micromag/screens/lazy: its manager needs the patterns generated by the build
import createLazyScreensManager from '../../../../screens/src/lazy/createLazyScreensManager';
import ViewerContainerBase from '../ViewerContainerBase';

const createLoaders = (types: string[]) => {
    const calls: string[] = [];
    const resolvers: Record<string, () => void> = {};
    const loaders = types.reduce(
        (map, type) => ({
            ...map,
            [type]: () => {
                calls.push(type);
                return new Promise<ElementType>((resolve) => {
                    resolvers[type] = () =>
                        resolve(() => createElement('div', { 'data-test-screen': type }));
                });
            },
        }),
        {},
    );
    // The patterns of the story parser (no medias, fonts or theme in these stories)
    const manager = createLazyScreensManager(loaders, { medias: {}, fonts: {}, theme: {} });
    const resolve = async (resolveTypes: string[]) => {
        resolveTypes.forEach((type) => resolvers[type]());
        await new Promise((done) => setTimeout(done, 0));
    };
    return { manager, calls, resolve };
};

const story = {
    id: 'story',
    title: 'Lazy screens',
    components: ['text', 'video', 'quiz', 'text', 'video', 'text'].map((type, index) => ({
        id: `screen-${index + 1}`,
        type,
    })),
};

const renderViewer = (manager, screen = 'screen-3') => {
    function TestScreensProvider({ children }: { children: ReactNode }) {
        return createElement(ScreensProvider, { manager, children });
    }
    return renderToString(
        createElement(ViewerContainerBase, {
            story,
            screen,
            memoryRouter: true,
            withoutRouter: true,
            // A known size: without it the viewer renders its screens once measured, in the browser
            width: 390,
            height: 844,
            screensProvider: TestScreensProvider,
        } as Parameters<typeof ViewerContainerBase>[0]),
    );
};

const renderedScreens = (html: string) =>
    [...html.matchAll(/data-test-screen="([^"]+)"/g)].map(([, type]) => type);

describe('Viewer with lazy screens', () => {
    test('loads only the screen types of the story, the current screen first', () => {
        const { manager, calls } = createLoaders(['text', 'video', 'quiz', 'map', 'survey']);
        renderViewer(manager);
        // Current screen (quiz), next (text), previous (video); never map or survey
        expect(calls).toEqual(['quiz', 'text', 'video']);
    });

    test('shows the screens once the current one and its neighbours are loaded', async () => {
        const { manager, resolve } = createLoaders(['text', 'video', 'quiz']);
        expect(renderedScreens(renderViewer(manager))).toEqual([]);

        // The current screen alone isn't enough: its neighbours could be reached right away
        await resolve(['quiz', 'text']);
        expect(renderedScreens(renderViewer(manager))).toEqual([]);

        await resolve(['video']);
        const screens = renderedScreens(renderViewer(manager));
        expect(screens).toContain('quiz');
        expect(screens.length).toBeGreaterThan(1);
    });
});

describe('waitForScreens', () => {
    const screens = ['text', 'video', 'quiz', 'map'].map((type) => ({ type }));

    test('the next screen and its neighbours are loaded before the viewer goes to it', async () => {
        const { manager, resolve } = createLoaders(['text', 'video', 'quiz', 'map']);
        manager.loadScreens(['text', 'video']);

        // From screen 1 (text) to screen 2 (video): video, quiz and text must be loaded
        let navigated = false;
        const waiting = waitForScreens(manager, screens, 1);
        expect(waiting).not.toBeNull();
        waiting?.then(() => {
            navigated = true;
        });

        await resolve(['text', 'video']);
        expect(navigated).toBe(false);

        await resolve(['quiz']);
        expect(navigated).toBe(true);
        expect(waitForScreens(manager, screens, 1)).toBeNull();
        // Screen 3 still waits for its next screen (map)
        expect(waitForScreens(manager, screens, 2)).not.toBeNull();
    });

    test('nothing to wait for with screens that are not lazy', () => {
        const manager = { screensLoaded: () => true, loadScreens: () => Promise.resolve() };
        expect(waitForScreens(manager, screens, 1)).toBeNull();
        expect(waitForScreens(null, screens, 1)).toBeNull();
    });
});

describe('getScreenTypesByDistance', () => {
    test('current screen, then the next and previous ones, then by distance', () => {
        const screens = ['a', 'b', 'c', 'd', 'e', 'f'].map((type) => ({ type }));
        expect(getScreenTypesByDistance(screens, 2)).toEqual(['c', 'd', 'b', 'e', 'a', 'f']);
        expect(getScreenTypesByDistance(screens, 0)).toEqual(['a', 'b', 'c', 'd', 'e', 'f']);
    });
});
