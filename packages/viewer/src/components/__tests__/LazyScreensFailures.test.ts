// @vitest-environment happy-dom

/**
 * The viewer with lazy screens when a screen can't be loaded (unstable network, chunk removed by a
 * deploy): the other screens are shown, the screen that failed shows its error (and onScreenError
 * is called), and it is loaded again later. Rendered in a DOM, with loaders resolved by hand.
 */
import { ElementType, ReactNode, act, createElement, useState } from 'react';
import { Root, createRoot } from 'react-dom/client';
import { afterEach, describe, expect, test, vi } from 'vitest';

import { ScreensProvider } from '@micromag/core/contexts';

// Not @micromag/screens/lazy: its manager needs the patterns generated by the build
import createLazyScreensManager from '../../../../screens/src/lazy/createLazyScreensManager';
import ViewerContainerBase from '../ViewerContainerBase';

// eslint-disable-next-line no-undef
(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;

type Outcome = 'resolve' | 'reject';

const createLoaders = (types: string[], { retryDelay = 0 } = {}) => {
    const calls: Record<string, number> = {};
    const pending: Record<string, ((outcome: Outcome) => void)[]> = {};
    const loaders = types.reduce(
        (map, type) => ({
            ...map,
            [type]: () => {
                calls[type] = (calls[type] || 0) + 1;
                return new Promise<ElementType>((resolve, reject) => {
                    pending[type] = [
                        ...(pending[type] || []),
                        (outcome) =>
                            outcome === 'resolve'
                                ? resolve(() => createElement('div', { 'data-test-screen': type }))
                                : reject(new Error(`Could not load ${type}`)),
                    ];
                });
            },
        }),
        {},
    );
    const manager = createLazyScreensManager(
        loaders,
        { medias: {}, fonts: {}, theme: {} },
        { retryDelay },
    );
    // Settles the attempts in progress for these types
    const settle = async (outcomes: Record<string, Outcome>) => {
        await act(async () => {
            Object.keys(outcomes).forEach((type) => {
                const callbacks = pending[type] || [];
                pending[type] = [];
                callbacks.forEach((callback) => callback(outcomes[type]));
            });
            await new Promise((done) => setTimeout(done, 10));
        });
    };
    return { manager, calls, settle };
};

const createStory = (types: string[]) => ({
    id: 'story',
    title: 'Lazy screens',
    components: types.map((type, index) => ({ id: `screen-${index + 1}`, type })),
});

let root: Root | null = null;
let container: HTMLElement | null = null;

afterEach(() => {
    act(() => root?.unmount());
    container?.remove();
    root = null;
    container = null;
});

const renderViewer = async (manager, story, { screen = 'screen-1' } = {}) => {
    const onScreenError = vi.fn();
    const changes: string[] = [];
    function TestScreensProvider({ children }: { children: ReactNode }) {
        return createElement(ScreensProvider, { manager, children });
    }
    function TestViewer() {
        // The host keeps the current screen (no router)
        const [screenId, setScreenId] = useState(screen);
        return createElement(ViewerContainerBase, {
            story,
            screen: screenId,
            withoutRouter: true,
            width: 390,
            height: 844,
            screensProvider: TestScreensProvider,
            onScreenError,
            onScreenChange: ({ id }: { id: string }) => {
                changes.push(id);
                setScreenId(id);
            },
        } as Parameters<typeof ViewerContainerBase>[0]);
    }
    container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
    await act(async () => {
        root?.render(createElement(TestViewer));
    });
    return { onScreenError, changes };
};

const press = async (key: string) => {
    await act(async () => {
        window.dispatchEvent(new KeyboardEvent('keydown', { key, bubbles: true }));
        await new Promise((done) => setTimeout(done, 10));
    });
};

// The neighbours that become active mount 200 ms later (ViewerScreen)
const waitForNeighbours = async () => {
    await act(async () => {
        await new Promise((done) => setTimeout(done, 250));
    });
};

const getSections = () => [...document.querySelectorAll('main section')];
const getCurrentIndex = () =>
    getSections().findIndex((section) => section.getAttribute('aria-hidden') === 'false');
const shownScreens = () =>
    [...document.querySelectorAll('[data-test-screen]')].map((it) =>
        it.getAttribute('data-test-screen'),
    );
const errorShownIn = (index: number) =>
    (getSections()[index]?.textContent || '').includes('could not be displayed');

describe('Viewer with lazy screens that fail to load', () => {
    test('the current screen fails: the others are shown, it shows its error', async () => {
        const { manager, settle } = createLoaders(['text', 'video', 'quiz']);
        const story = createStory(['text', 'video', 'quiz', 'text']);
        const { onScreenError } = await renderViewer(manager, story, { screen: 'screen-3' });
        expect(getSections()).toHaveLength(0);

        await settle({ quiz: 'reject', text: 'resolve', video: 'resolve' });

        expect(getSections()).toHaveLength(4);
        expect(getCurrentIndex()).toBe(2);
        expect(errorShownIn(2)).toBe(true);
        expect(shownScreens()).toEqual(expect.arrayContaining(['video', 'text']));
        expect(onScreenError).toHaveBeenCalled();
        expect(onScreenError.mock.calls[0][0].message).toBe('Could not load quiz');
    });

    test('the next screen fails: the current one is shown, the next one shows its error', async () => {
        const { manager, settle } = createLoaders(['text', 'video', 'quiz']);
        const story = createStory(['text', 'video', 'quiz']);
        await renderViewer(manager, story);

        await settle({ text: 'resolve', video: 'reject', quiz: 'resolve' });

        expect(getCurrentIndex()).toBe(0);
        expect(shownScreens()).toContain('text');
        expect(errorShownIn(1)).toBe(true);

        // The reader can go to it: it shows its error, and it is loaded again
        await press('ArrowRight');
        expect(getCurrentIndex()).toBe(1);
        expect(errorShownIn(1)).toBe(true);
    });

    test('a screen fails during a held navigation: the viewer goes anyway', async () => {
        const { manager, settle } = createLoaders(['text', 'video', 'map']);
        const story = createStory(['text', 'video', 'map']);
        const { changes } = await renderViewer(manager, story);
        await settle({ text: 'resolve', video: 'resolve' });
        expect(getCurrentIndex()).toBe(0);

        // Screen 2 needs its next screen (map), still loading: the navigation is held
        await press('ArrowRight');
        expect(changes).toEqual([]);
        expect(getCurrentIndex()).toBe(0);

        await settle({ map: 'reject' });
        await waitForNeighbours();
        expect(changes).toEqual(['screen-2']);
        expect(getCurrentIndex()).toBe(1);
        expect(shownScreens()).toEqual(expect.arrayContaining(['text', 'video']));
        expect(errorShownIn(2)).toBe(true);
    });

    test('a screen that fails once is loaded again, then shown', async () => {
        const { manager, calls, settle } = createLoaders(['text', 'video'], { retryDelay: 20 });
        const story = createStory(['text', 'video']);
        const { onScreenError } = await renderViewer(manager, story);

        await settle({ text: 'reject', video: 'resolve' });
        expect(errorShownIn(0)).toBe(true);
        expect(onScreenError).toHaveBeenCalledTimes(1);

        // The automatic attempt, after the delay
        await act(async () => {
            await new Promise((done) => setTimeout(done, 40));
        });
        expect(calls.text).toBe(2);
        await settle({ text: 'resolve' });

        expect(errorShownIn(0)).toBe(false);
        expect(shownScreens()).toContain('text');
        expect(onScreenError).toHaveBeenCalledTimes(1);
    });

    test('a screen that keeps failing is tried again only when the reader gets near it', async () => {
        const { manager, calls, settle } = createLoaders(['text', 'video', 'quiz'], {
            retryDelay: 20,
        });
        const story = createStory(['text', 'video', 'text', 'quiz']);
        await renderViewer(manager, story);
        await settle({ text: 'resolve', video: 'resolve', quiz: 'reject' });
        expect(calls.quiz).toBe(1);

        // One automatic attempt, then no more
        await act(async () => {
            await new Promise((done) => setTimeout(done, 40));
        });
        await settle({ quiz: 'reject' });
        await act(async () => {
            await new Promise((done) => setTimeout(done, 60));
        });
        expect(calls.quiz).toBe(2);

        // Screen 3 is next to it: one more attempt
        await press('ArrowRight');
        await press('ArrowRight');
        expect(getCurrentIndex()).toBe(2);
        expect(calls.quiz).toBe(3);
        await settle({ quiz: 'resolve' });
        await waitForNeighbours();
        expect(shownScreens()).toContain('quiz');
    });

    test('a tap back to the current screen cancels a held navigation', async () => {
        const { manager, settle } = createLoaders(['text', 'video', 'map']);
        const story = createStory(['text', 'video', 'map']);
        const { changes } = await renderViewer(manager, story);
        await settle({ text: 'resolve', video: 'resolve' });

        await press('ArrowRight');
        await press('ArrowLeft');
        await settle({ map: 'resolve' });

        expect(changes).toEqual([]);
        expect(getCurrentIndex()).toBe(0);
    });
});
